#' @importFrom dplyr bind_rows
#' @export
#'
#' @title
#' Rotating Panels
#' @description
#' Generates the sequence of sub-panels of an A-0-0 rotating panel scheme
#' (4-0-0 or 5-0-0) for \code{period} periods: each sub-panel is observed
#' \code{A} consecutive periods and then leaves the sample. The basic block
#' from \code{\link{basic_rotating_panels}} is repeated, renumbering the
#' sub-panels, until the requested number of periods is reached.
#'
#' @details
#' The schemes used in the package are 4-0-0 (\code{A = 4, B = 0, C = 0},
#' 75\% overlap between consecutive periods), 5-0-0 (\code{A = 5, B = 0,
#' C = 0}, 80\%) and 2-2-2. The 2-2-2 scheme is generated by
#' \code{\link{rotating_panel_222}}.
#'
#' Several schemes can be combined side by side with \code{cbind()}, using a
#' different \code{value_initial} for each one (see the examples).
#'
#' @return A \code{data.frame} with \code{period} rows and \code{A} columns,
#'   named with consecutive letters starting at \code{value_initial}. Each
#'   cell is the label (letter + number) of the sub-panel visited in that
#'   period, e.g. \code{"A1"}.
#'
#' @author Jose Fernando Zea Castro <jfzeac at unal.edu.co>,
#'   Hugo Andres Gutierrez Rojas <andres.gutierrez at cepal.org>,
#'   Stalyn Yasid Guerrero Gomez <syguerrerog at unal.edu.co>,
#'   Yury Vanessa Ochoa Montes <yury.ochoa at urosario.edu.co>
#'
#' @param A Integer. Number of consecutive periods a sub-panel is observed:
#'   4 for scheme 4-0-0, 5 for scheme 5-0-0.
#' @param B Integer. 0 for schemes 4-0-0 and 5-0-0.
#' @param C Integer. 0 for schemes 4-0-0 and 5-0-0.
#' @param period Integer (>= 1). Total number of periods required.
#' @param value_initial A single uppercase letter used for the first column.
#'   Default \code{"A"}.
#'
#' @seealso \code{\link{basic_rotating_panels}},
#'   \code{\link{rotating_panel_222}}
#'
#' @examples
#' # Scheme 5-0-0 for 12 periods
#' rotating_panels(A = 5, B = 0, C = 0, period = 12)
#'
#' # Three 4-0-0 schemes side by side (12 rotation groups, letters A to L)
#' cbind(
#'   rotating_panels(4, 0, 0, period = 8, value_initial = "A"),
#'   rotating_panels(4, 0, 0, period = 8, value_initial = "E"),
#'   rotating_panels(4, 0, 0, period = 8, value_initial = "I")
#' )
#'
#' # Scheme 2-2-2
#' rotating_panel_222(8)
rotating_panels <- function(A, B, C, period,
                            value_initial = "A") {
  
  if (!is.numeric(A) || !is.numeric(B) || !is.numeric(C)) {
    stop("A, B, and C must be numeric")
  }
  
  if (!is.character(value_initial) || nchar(value_initial) != 1 || !grepl("[A-Z]", value_initial)) {
    stop("value_initial must be a character string of length 1 that corresponds to a letter in the English alphabet")
  }
  
  Basic_panels <-  basic_rotating_panels(A, B, C)
  num_basic_period <- nrow(Basic_panels)
  
  if (period < num_basic_period) {
    result_panels <- Basic_panels[1:period, ]
  }
  
  if (period == num_basic_period) {
    result_panels <- basic_rotating_panels(A, B, C)
  }
  
  if ((period >  num_basic_period) &
      (period %% num_basic_period) == 0) {
    repetition <- period / num_basic_period
    
    Basic_panels <- basic_rotating_panels(A, B, C)
    result_panels <- vector(mode = "list", length = repetition)
    result_panels[[1]] <- Basic_panels
    
    for (i in 1:(repetition - 1)) {
      valorSum <- max(result_panels[[i]][, 1])
      result_panels[[i + 1]] <- Basic_panels + valorSum
    }
    result_panels <- bind_rows(result_panels)
    
  }
  
  if ((period >  num_basic_period) &
      (period %% num_basic_period) > 0) {
    repetition <- ceiling(period / num_basic_period)
    
    Basic_panels <- basic_rotating_panels(A, B, C)
    result_panels <- vector(mode = "list", length = repetition)
    result_panels[[1]] <- Basic_panels
    
    for (i in 1:(repetition - 1)) {
      valorSum <- max(result_panels[[i]][, 1])
      result_panels[[i + 1]] <- Basic_panels + valorSum
    }
    result_panels <- bind_rows(result_panels)
    result_panels <- result_panels[1:period, ]
  }
  
  
  posicion_value_initial <- which(LETTERS == value_initial)
  letras <- LETTERS[-(1:(posicion_value_initial - 1))]
  if (value_initial == "A")
    letras <- LETTERS
  
  names(result_panels) <- letras[1:ncol(result_panels)]
  
  for (i in 1:nrow(result_panels)) {
    for (j in 1:ncol(result_panels)) {
      result_panels[i, j] <- paste0(colnames(result_panels)[j],
                                    result_panels[i, j])
    }
  }
  
  return(result_panels) 
}