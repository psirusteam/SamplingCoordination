#' @importFrom dplyr rename_all
#' @export
#'
#' @title Basic Rotating Panels
#' @description
#' Generates the basic block of a rotating panel scheme. It is intended for
#' the A-0-0 schemes used in the package, 4-0-0 and 5-0-0: each sub-panel is
#' observed during \code{A} consecutive periods and then leaves the sample.
#' The block is the minimal sequence that \code{\link{rotating_panels}}
#' repeats to cover any number of periods.
#'
#' @details
#' Each row of the result is a period and each column (\code{P1}, \ldots,
#' \code{PA}) is a rotation group. The cell value is the number of the
#' sub-panel of that group visited in that period. In every period exactly one
#' group changes sub-panel, so the overlap between two consecutive periods is
#' \eqn{(A - 1) / A}: 75\% for 4-0-0 and 80\% for 5-0-0.
#'
#' The schemes used in the package are 4-0-0, 5-0-0 and 2-2-2. Use
#' \code{B = 0} and \code{C = 0} for 4-0-0 and 5-0-0. The 2-2-2 scheme
#' (observed 2 periods, rests 2, observed 2 more) is generated by
#' \code{\link{rotating_panel_222}}.
#'
#' @return A \code{data.frame} with one row per period of the basic block and
#'   \code{A} columns (\code{P1}, \ldots, \code{PA}) with the sub-panel number.
#' @author Jose Fernando Zea Castro <jfzeac at unal.edu.co>, Hugo Andres
#'   Gutierrez Rojas <andres.gutierrez at cepal.org>, Stalyn Yasid Guerrero
#'   Gomez <syguerrerog at unal.edu.co>
#' @param A Integer. Number of consecutive periods a sub-panel is observed:
#'   4 for scheme 4-0-0, 5 for scheme 5-0-0.
#' @param B Integer. Number of rest periods; 0 for schemes 4-0-0 and 5-0-0.
#' @param C Integer. 0 for schemes 4-0-0 and 5-0-0.
#' @seealso \code{\link{rotating_panels}}, \code{\link{rotating_panel_222}}
#' @examples
#' # 5-0-0: five consecutive periods, 80% overlap
#' basic_rotating_panels(A = 5, B = 0, C = 0)
#'
#' # 4-0-0: four consecutive periods, 75% overlap
#' basic_rotating_panels(A = 4, B = 0, C = 0)

basic_rotating_panels <- function(A, B, C) {
  
  if (!is.numeric(A) || !is.numeric(B) || !is.numeric(C)) {
    stop("A, B, and C must be numeric")
  }
  
  length_period <- 2 * (A + B) 
  number_panels <- 1 + (B / A) 
  
  if (B == 0) {
    length_period <- A + B
    number_panels <- 1
  }
  
  basic_cycle <- rep(1:number_panels, rep(A, number_panels))
  basic_cycle_rep <- rep(basic_cycle, 2)
  
  if (B == 0) {
    basic_cycle_rep <- basic_cycle
  }
  
  num_columnas <- A
  
  lista <- vector(mode = "list", length = num_columnas)
  lista[[1]] <- basic_cycle_rep
  for (i in 1:(A - 1)) {
    lista[[i + 1]] <-
      c(dplyr::lead(basic_cycle_rep, i)[-(length_period:(length_period - (i -
                                                                            1)))],
        rep(number_panels + 1, i))
  }
  
  df <- as.data.frame(do.call(cbind, lista))
  df <- rename_all(df , function(.x) gsub(pattern = "V", 
                                          replacement = "P",x = .x))
  return(df)
}